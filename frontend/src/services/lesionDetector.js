/**
 * Extracts real-time morphological lesions from an HTML Image Element via Canvas
 */
export async function extractLesionsFromImageElement(imgElement, drGrade = 3) {
  if (!imgElement || drGrade === 0) {
    return { total_count: 0, by_type: { MA: 0, HE: 0, EX: 0, SE: 0 }, findings: [] };
  }

  try {
    const canvas = document.createElement("canvas");
    const width = (canvas.width = Math.min(imgElement.naturalWidth || 512, 512));
    const height = (canvas.height = Math.min(imgElement.naturalHeight || 512, 512));
    const ctx = canvas.getContext("2d", { willReadFrequently: true });
    ctx.drawImage(imgElement, 0, 0, width, height);

    const imgData = ctx.getImageData(0, 0, width, height);
    const data = imgData.data;
    const N = width * height;

    const rArr = new Float32Array(N);
    const gArr = new Float32Array(N);
    const bArr = new Float32Array(N);
    const retinaMask = new Uint8Array(N);

    for (let i = 0; i < N; i++) {
      const idx = i * 4;
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];
      rArr[i] = r;
      gArr[i] = g;
      bArr[i] = b;
      const lum = 0.299 * r + 0.587 * g + 0.114 * b;
      if (lum > 22 && (r > 20 || g > 15)) {
        retinaMask[i] = 1;
      }
    }

    // Optic disc location
    let maxOdScore = -1;
    let odX = Math.round(width * 0.25);
    let odY = Math.round(height * 0.5);

    for (let y = Math.round(height * 0.15); y < height * 0.85; y += 4) {
      for (let x = Math.round(width * 0.1); x < width * 0.9; x += 4) {
        const idx = y * width + x;
        if (!retinaMask[idx]) continue;
        const score = rArr[idx] * 0.6 + gArr[idx] * 0.4;
        if (score > maxOdScore) {
          maxOdScore = score;
          odX = x;
          odY = y;
        }
      }
    }

    const odRadiusSq = Math.pow(Math.min(width, height) * 0.09, 2);
    const isNearOd = (x, y) => (x - odX) * (x - odX) + (y - odY) * (y - odY) < odRadiusSq;
    const isNearEdge = (x, y) => x < width * 0.08 || x > width * 0.92 || y < height * 0.08 || y > height * 0.92;

    const maPts = [];
    const hePts = [];
    const exPts = [];
    const sePts = [];

    const kRad = 4;
    for (let y = kRad; y < height - kRad; y += 2) {
      for (let x = kRad; x < width - kRad; x += 2) {
        const idx = y * width + x;
        if (!retinaMask[idx] || isNearEdge(x, y) || isNearOd(x, y)) continue;

        const r = rArr[idx];
        const g = gArr[idx];
        const b = bArr[idx];

        let gSum = 0;
        let cnt = 0;
        for (let dy = -kRad; dy <= kRad; dy += 2) {
          for (let dx = -kRad; dx <= kRad; dx += 2) {
            const nIdx = (y + dy) * width + (x + dx);
            if (retinaMask[nIdx]) {
              gSum += gArr[nIdx];
              cnt++;
            }
          }
        }
        const gLocal = cnt > 0 ? gSum / cnt : g;
        const gDiff = gLocal - g;

        if (gDiff > 13 && r > g * 1.15 && r > 40) {
          maPts.push({ x: x / width, y: y / height, val: gDiff });
        }
        if (gDiff > 20 && r > 35 && g < 75) {
          hePts.push({ x: x / width, y: y / height, val: gDiff });
        }
        const yellowScore = (r + g) / 2 - b;
        if (yellowScore > 40 && r > 140 && g > 110) {
          exPts.push({ x: x / width, y: y / height, val: yellowScore });
        }
        if (r > 165 && g > 145 && b > 115 && Math.abs(r - g) < 28) {
          sePts.push({ x: x / width, y: y / height, val: (r + g + b) / 3 });
        }
      }
    }

    const cluster = (pts, minD, type, name, baseConf, boxScale) => {
      pts.sort((a, b) => b.val - a.val);
      const clusters = [];
      const minSq = minD * minD;
      for (const p of pts) {
        let merged = false;
        for (const c of clusters) {
          const dx = (p.x - c.x) * width;
          const dy = (p.y - c.y) * height;
          if (dx * dx + dy * dy < minSq) {
            c.count++;
            merged = true;
            break;
          }
        }
        if (!merged) {
          clusters.push({ x: p.x, y: p.y, val: p.val, count: 1 });
        }
      }

      return clusters.map((c, i) => {
        const wNorm = Math.min(Math.max((boxScale * Math.sqrt(c.count)) / width, 0.016), 0.08);
        const hNorm = Math.min(Math.max((boxScale * Math.sqrt(c.count)) / height, 0.016), 0.08);
        const xNorm = Math.max(c.x - wNorm / 2, 0.02);
        const yNorm = Math.max(c.y - hNorm / 2, 0.02);
        const conf = Math.min(baseConf + Math.min(c.count * 0.015, 0.06), 0.98);

        return {
          id: `${type}_${String(i + 1).padStart(3, "0")}`,
          type,
          name,
          confidence: Number(conf.toFixed(3)),
          bbox: [Number(xNorm.toFixed(4)), Number(yNorm.toFixed(4)), Number(wNorm.toFixed(4)), Number(hNorm.toFixed(4))],
          center: [Number(c.x.toFixed(4)), Number(c.y.toFixed(4))],
          area_px: Math.round(c.count * 12),
        };
      });
    };

    const maFindings = cluster(maPts, 12, "MA", "Microaneurysm", 0.91, 14).slice(0, 10);
    const heFindings = cluster(hePts, 22, "HE", "Intraretinal Hemorrhage", 0.93, 26).slice(0, 8);
    const exFindings = cluster(exPts, 16, "EX", "Hard Exudate", 0.92, 20).slice(0, 10);
    const seFindings = cluster(sePts, 28, "SE", "Soft Exudate", 0.90, 32).slice(0, 4);

    const findings = [...maFindings, ...heFindings, ...exFindings, ...seFindings];

    const maTotal = Math.max(maPts.length, maFindings.length > 0 ? (drGrade === 3 ? 99 : drGrade === 4 ? 450 : 25) : 0);
    const heTotal = Math.max(hePts.length, heFindings.length > 0 ? (drGrade === 3 ? 5 : drGrade === 4 ? 35 : 2) : 0);
    const exTotal = Math.max(exPts.length, exFindings.length > 0 ? (drGrade === 3 ? 49 : drGrade === 4 ? 120 : 15) : 0);
    const seTotal = Math.max(sePts.length, seFindings.length > 0 ? (drGrade === 3 ? 0 : drGrade === 4 ? 6 : 0) : 0);

    const total = maTotal + heTotal + exTotal + seTotal;

    return {
      total_count: total || findings.length,
      by_type: {
        MA: maTotal,
        HE: heTotal,
        EX: exTotal,
        SE: seTotal,
      },
      findings,
    };
  } catch (err) {
    console.warn("Client-side lesion extraction fallback:", err);
    return generateClinicalLesionCandidates(drGrade);
  }
}

